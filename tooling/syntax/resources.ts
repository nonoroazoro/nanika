import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseRawGrammar } from "vscode-textmate";

import manifest from "../../apps/desktop/frontend/src/syntax/grammars/manifest.json";
import { SYNTAX_FOREGROUNDS, TOKEN_COLORS } from "../../apps/desktop/frontend/src/syntax/palette";
import packages from "../../package.json";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const syntax = join(root, "apps/desktop/frontend/src/syntax");
const mode = process.argv[2] ?? "check";
if (!["check", "update", "vendor"].includes(mode))
{
    throw new Error("Usage: bun tooling/syntax/resources.ts check|update|vendor [pinned upstream source directories]");
}
if (mode === "vendor")
{
    const upstreams = Object.entries(manifest.upstreams);
    const directories = process.argv.slice(3);
    if (directories.length !== upstreams.length)
    {
        throw new Error(`Provide pinned source directories in order: ${upstreams.map(([name]) => name).join(", ")}.`);
    }
    for (const [index, [name, upstream]] of upstreams.entries())
    {
        const directory = directories[index];
        if (!directory)
        {
            throw new Error(`Missing source directory for ${name}.`);
        }
        for (const entry of Object.values(manifest.grammars).filter(candidate => candidate.upstream === name))
        {
            const raw = await readFile(join(directory, entry.source), "utf8");
            if (createHash("sha256").update(raw).digest("hex") !== entry.sha256)
            {
                throw new Error(`Upstream grammar differs from the pinned source: ${entry.source}`);
            }
            const grammar = parseRawGrammar(raw, entry.source);
            await writeFile(join(syntax, "grammars", entry.asset), `${JSON.stringify(grammar)}\n`);
        }
        // Review THIRD_PARTY_NOTICES.md when updating sources; whole upstream notices include unrelated components.
        await Promise.all(upstream.notices.map(async notice =>
        {
            const text = await readFile(join(directory, notice.path), "utf8");
            if (createHash("sha256").update(text).digest("hex") !== notice.sha256)
            {
                throw new Error(`Upstream notice differs from the pinned source: ${name}/${notice.path}`);
            }
        }));
    }
}
const digest = createHash("sha256");
digest.update(JSON.stringify(manifest));
digest.update(packages.dependencies["vscode-textmate"]);
digest.update(packages.dependencies["vscode-oniguruma"]);
for (const entry of Object.values(manifest.grammars))
{
    const raw = await readFile(join(syntax, "grammars", entry.asset), "utf8");
    const grammar = parseRawGrammar(raw, entry.asset);
    const scope = Object.entries(manifest.grammars).find(([, candidate]) => candidate === entry)?.[0];
    if (grammar.scopeName !== scope)
    {
        throw new Error(`Grammar scope does not match its manifest entry: ${entry.asset}`);
    }
    const references = new Set<string>();
    _grammarReferences(grammar, references);
    const missing = [...references].filter(reference => !Object.hasOwn(manifest.grammars, reference));
    if (JSON.stringify(missing.sort()) !== JSON.stringify([...entry.optionalScopes].sort()))
    {
        throw new Error(`Unreviewed grammar dependencies in ${entry.asset}: ${missing.join(", ")}`);
    }
    for (const target of entry.injectTo)
    {
        if (!Object.hasOwn(manifest.grammars, target))
        {
            throw new Error(`Missing injection target ${target} for ${entry.asset}`);
        }
    }
    digest.update(raw);
}
for (
    const name of [
        "palette.ts",
        "themes/light.json",
        "themes/dark.json",
        "themes/manifest.json",
        "detect.ts",
        "configuration.ts",
        "languages.ts",
        "limits.ts",
        "SyntaxEngine.ts"
    ]
)
{
    digest.update(await readFile(join(syntax, name)));
}
const cssPath = join(syntax, "tokens.css");
const css = [
    "/* Generated by tooling/syntax/resources.ts from the bundled VS Code themes. */",
    ...Object.entries(SYNTAX_FOREGROUNDS).map(([theme, foreground]) =>
    {
        return `[data-syntax-theme="${theme}"] { color: ${foreground}; }`;
    }),
    ...TOKEN_COLORS.slice(1).map((color, index) => `.syntax-token-${index + 1} { color: ${color}; }`),
    ".syntax-source-segment { display: block; contain: layout style; }",
    ""
].join("\n");
if (mode === "check")
{
    if (await readFile(cssPath, "utf8") !== css)
    {
        throw new Error("Syntax theme CSS changed. Run bun tooling/syntax/resources.ts update.");
    }
}
else
{
    await writeFile(cssPath, css);
}
const output =
    `// Generated by tooling/syntax/resources.ts. Cache format remains v1.\nexport const SYNTAX_FINGERPRINT = "${
        digest.digest("hex")
    }";\n`;
const path = join(syntax, "fingerprint.ts");
if (mode === "check")
{
    if (await readFile(path, "utf8") !== output)
    {
        throw new Error("Syntax assets changed. Run bun tooling/syntax/resources.ts update.");
    }
}
else
{
    await writeFile(path, output);
}
console.log(`Syntax resources: ${mode} passed (${Object.keys(manifest.grammars).length} grammars).`);

/**
 * Collect external scope dependencies; repository-local rules are resolved by TextMate.
 *
 * @param node Grammar subtree
 * @param scopes External scope names, without repository fragments
 */
function _grammarReferences(node: unknown, scopes: Set<string>): void
{
    if (!node || typeof node !== "object")
    {
        return;
    }
    if ("include" in node && typeof node.include === "string" && !/^[#$]/.test(node.include))
    {
        const scope = node.include.split("#")[0];
        if (scope)
        {
            scopes.add(scope);
        }
    }
    for (const value of Object.values(node))
    {
        _grammarReferences(value, scopes);
    }
}
